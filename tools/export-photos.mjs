import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire('C:/Users/glina/route-story-spike/package.json');
const { chromium } = require('playwright');
const b = await chromium.launch({ channel: 'msedge', headless: true });
const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
p.on('pageerror', e => console.log('pageerror:', e.message));
await p.goto('http://localhost:4180/');
await p.setInputFiles('#file', 'samples/samarkand-bukhara.gpx');
await p.waitForFunction(() => window.__app.scene);
await p.fill('#note', '300 км пустыни — и ни одного прокола');
await p.setInputFiles('#photos', ['out/ph-gps.jpg', 'out/ph-time.jpg']);
await p.waitForFunction(() => window.__app.state.o.photos.length === 2);
await p.selectOption('#res', 'sd'); await p.selectOption('#duration', '20');
await p.click('#export');
await p.waitForFunction(() => window.__lastExport || !document.getElementById('err').hidden, null, { timeout: 600000 });
const r = await p.evaluate(async () => { const x = window.__lastExport; const buf = new Uint8Array(await (await fetch(x.url)).arrayBuffer()); let s = ''; for (let i = 0; i < buf.length; i += 0x8000) s += String.fromCharCode.apply(null, buf.subarray(i, i + 0x8000)); return { b64: btoa(s), arr: window.__app.scene.photos.map(q => q.arr) }; });
writeFileSync('out/with-photos.mp4', Buffer.from(r.b64, 'base64'));
console.log('photo times', r.arr.map(x => x.toFixed(2)).join(', '));
await b.close();
